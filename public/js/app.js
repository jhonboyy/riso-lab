class RisoLab {
	constructor() {
		this.img = null;
		this.mainCanvas = document.getElementById('mainCanvas');
		this.cachedChannels = { red: null, green: null, blue: null };
		this.layerCache = { red: null, green: null, blue: null };
		this.layerSignature = { red: null, green: null, blue: null };

		this.menu = document.querySelector('.menu');
		this.channelLabel = document.getElementById('channel');
		this.fileInput = document.getElementById('fileInput');
		this.fileUploadLabel = document.querySelector('.custom-file-upload');

		this.params = {
			redColor: 'RED',
			greenColor: 'GREEN',
			blueColor: 'BLUE',
			redPattern: 'circle',
			greenPattern: 'circle',
			bluePattern: 'circle',
			redFreq: 5,
			greenFreq: 5,
			blueFreq: 5,
			redAngle: 45,
			greenAngle: 45,
			blueAngle: 45,
			redIntensity: 127,
			greenIntensity: 127,
			blueIntensity: 127
		};

		this.isCoverVisible = true;
		this.debounceTimers = {};

		this.init();
	}

	init() {
		this.setupColorButtons();
		this.setupPatternButtons();
		this.setupInputs();
		this.setupDownloadButtons();
		this.setupFileInput();
		this.setupHoverHelp();
		this.setupClickOutside();
		this.setupZoomLoupe();
	}

	buildLayer(layer) {
		const srcChannel = CHANNEL_MAP[layer];
		const channelImg = this.cachedChannels[srcChannel];
		if (!channelImg) return null;

		const signature = [
			this.params[layer + 'Color'],
			this.params[layer + 'Pattern'],
			this.params[layer + 'Freq'],
			this.params[layer + 'Angle'],
			this.params[layer + 'Intensity'],
			this.img.width,
			this.img.height
		].join('|');

		if (this.layerSignature[layer] === signature) {
			return this.layerCache[layer];
		}

		const halftoned = halftoneImage(
			channelImg,
			this.params[layer + 'Pattern'],
			this.params[layer + 'Freq'],
			this.params[layer + 'Angle'],
			this.params[layer + 'Intensity']
		);

		if (!halftoned) return null;

		const riso = new Riso(this.params[layer + 'Color'], this.img.width, this.img.height);
		riso.image(halftoned, 0, 0, this.img.width, this.img.height);

		this.layerSignature[layer] = signature;
		this.layerCache[layer] = riso;
		return riso;
	}

	render() {
		if (!this.img) return;
		const layers = CHANNELS.map((layer) => this.buildLayer(layer)).filter(Boolean);
		if (layers.length === CHANNELS.length) {
			drawRiso(layers, this.mainCanvas);
		}
	}

	setupColorButtons() {
		const buttons = {
			red: document.getElementById('buttonred'),
			green: document.getElementById('buttongreen'),
			blue: document.getElementById('buttonblue')
		};
		Object.entries(buttons).forEach(([channel, btn]) => {
			btn.addEventListener('click', () => this.showColorPicker(channel));
		});
		this.colorButtons = buttons;
	}

	showColorPicker(channel) {
		this.openPopover('coloursdiv', (popover) => {
			RISOCOLORS.forEach((c, i) => {
				const div = document.createElement('div');
				div.classList.add('colour');
				div.style.cssText = 'cursor: pointer; background-color: rgb(' + c.color.join(',') + ')';
				div.addEventListener('mouseover', () => {
					this.channelLabel.textContent = RISO_COLORS_ALIAS[i];
				});
				div.addEventListener('mouseout', () => {
					this.channelLabel.textContent = 'Colours';
				});
				div.addEventListener('click', () => {
					this.setChannelColor(channel, c.name, c.color);
					popover.remove();
				});
				popover.appendChild(div);
			});
		});
	}

	setChannelColor(channel, name, color) {
		this.params[channel + 'Color'] = name;
		const btn = this.colorButtons[channel];
		btn.style.backgroundColor = 'rgb(' + color.join(',') + ')';
		this.adjustTextColor(btn);
		this.render();
	}

	adjustTextColor(button) {
		const bg = window.getComputedStyle(button).backgroundColor;
		const rgb = bg.match(/\d+/g).map(Number);
		if (rgb.length >= 3) {
			const brightness = (rgb[0] * 299 + rgb[1] * 587 + rgb[2] * 114) / 1000;
			button.style.color = brightness < 128 ? 'white' : '';
		}
	}

	setupPatternButtons() {
		const patterns = {
			red: document.getElementById('patternRed'),
			green: document.getElementById('patternGreen'),
			blue: document.getElementById('patternBlue')
		};
		Object.entries(patterns).forEach(([channel, btn]) => {
			btn.addEventListener('click', () => this.showPatternPicker(channel));
		});
		this.patternButtons = patterns;
	}

	showPatternPicker(channel) {
		this.openPopover('patternsdiv', (popover) => {
			PATTERNS.forEach((el) => {
				const p = document.createElement('p');
				const label = el.charAt(0).toUpperCase() + el.slice(1);
				p.textContent = label;
				p.style.cssText =
					'cursor: pointer; display: grid; margin: 0; padding: 0; height: max-content; width: max-content; text-decoration: none;';
				p.addEventListener('mouseover', () => {
					p.style.textDecoration = 'underline';
				});
				p.addEventListener('mouseout', () => {
					p.style.textDecoration = 'none';
				});
				p.addEventListener('click', () => {
					this.setChannelPattern(channel, el, label);
					popover.remove();
				});
				popover.appendChild(p);
			});
		});
	}

	setChannelPattern(channel, pattern, label) {
		this.params[channel + 'Pattern'] = pattern;
		this.patternButtons[channel].textContent = label;
		this.render();
	}

	openPopover(className, build) {
		const existing = this.menu.querySelector('.' + className);
		if (existing) existing.remove();

		const popover = document.createElement('div');
		popover.classList.add(className);
		build(popover);
		this.menu.appendChild(popover);
		return popover;
	}

	setupInputs() {
		const fields = [
			{ id: 'frecuencyRed', key: 'redFreq' },
			{ id: 'frecuencyGreen', key: 'greenFreq' },
			{ id: 'frecuencyBlue', key: 'blueFreq' },
			{ id: 'angleRed', key: 'redAngle' },
			{ id: 'angleGreen', key: 'greenAngle' },
			{ id: 'angleBlue', key: 'blueAngle' },
			{ id: 'intensityRed', key: 'redIntensity' },
			{ id: 'intensityGreen', key: 'greenIntensity' },
			{ id: 'intensityBlue', key: 'blueIntensity' }
		];

		fields.forEach(({ id, key }) => {
			const el = document.getElementById(id);
			const isFreq = id.startsWith('frecuency');
			el.addEventListener('blur', () => this.applyInputValue(el, key, isFreq, false));
			el.addEventListener('change', () => this.applyInputValue(el, key, isFreq, false));
			el.addEventListener('keydown', (e) => {
				if (e.key === 'Enter') {
					e.preventDefault();
					this.applyInputValue(el, key, isFreq, true);
				}
			});
		});
	}

	applyInputValue(el, key, isFreq, immediate) {
		let val = parseInt(el.value);
		if (isFreq && (isNaN(val) || val < 1)) val = 1;
		if (!isFreq && isNaN(val)) val = 0;
		this.params[key] = val;
		el.value = val;
		if (immediate) this.render();
		else this.debounceRender();
	}

	debounceRender() {
		clearTimeout(this.debounceTimers.render);
		this.debounceTimers.render = setTimeout(() => this.render(), 150);
	}

	setupDownloadButtons() {
		this.coverBtn = document.getElementById('downloadCOVERButton');
		this.pdfBtn = document.getElementById('downloadPDFButton');
		this.jpgBtn = document.getElementById('downloadJPGButton');

		this.coverBtn.addEventListener('click', () => this.setDownloadMode('pdf'));
		this.pdfBtn.addEventListener('click', () => {
			this.setDownloadMode('cover');
			this.exportLayers();
		});
		this.jpgBtn.addEventListener('click', () => {
			this.setDownloadMode('cover');
			this.exportJPG();
		});
	}

	setDownloadMode(mode) {
		this.isCoverVisible = mode === 'cover';
		this.coverBtn.style.visibility = mode === 'cover' ? 'visible' : 'hidden';
		this.pdfBtn.style.visibility = mode === 'pdf' ? 'visible' : 'hidden';
		this.jpgBtn.style.visibility = mode === 'pdf' ? 'visible' : 'hidden';
	}

	setupFileInput() {
		this.fileInput.addEventListener('change', (e) => {
			const file = e.target.files[0];
			if (!file) return;
			this.loadImage(file);
		});
	}

	setupHoverHelp() {
		const menuText = document.getElementById('menuText');
		const defaultText = menuText.innerHTML;

		Object.entries(HELP_TEXTS).forEach(([id, text]) => {
			const el = document.getElementById(id);
			if (!el) return;
			el.addEventListener('mouseover', () => {
				menuText.innerHTML = text;
			});
			el.addEventListener('mouseout', () => {
				menuText.innerHTML = defaultText;
			});
		});
	}

	setupClickOutside() {
		document.addEventListener('click', (event) => {
			this.menu.querySelectorAll('.coloursdiv, .patternsdiv').forEach((popover) => {
				if (!this.menu.contains(event.target) && !popover.contains(event.target)) {
					popover.remove();
				}
			});
		});
	}

	setupZoomLoupe() {
		const canHover = window.matchMedia('(hover: hover) and (pointer: fine)').matches;
		const canTouch = navigator.maxTouchPoints > 0;
		if (!canHover && !canTouch) return;

		const canvasWrap = this.mainCanvas.closest('.canvas');
		if (!canvasWrap) return;

		const ZOOM_SIZE = 200;
		const ZOOM_LEVELS = [100, 48, 24];
		let zoomIndex = 1;
		let lastX = 0;
		let lastY = 0;
		let suppressClick = false;

		const loupe = document.createElement('div');
		loupe.classList.add('zoom-loupe');
		loupe.style.display = 'none';

		const zoomCanvas = document.createElement('canvas');
		zoomCanvas.classList.add('zoom-canvas');
		zoomCanvas.width = ZOOM_SIZE;
		zoomCanvas.height = ZOOM_SIZE;
		loupe.appendChild(zoomCanvas);
		canvasWrap.appendChild(loupe);

		const zoomCtx = zoomCanvas.getContext('2d');

		const drawLoupe = (clientX, clientY) => {
			const rect = this.mainCanvas.getBoundingClientRect();
			const wrapRect = canvasWrap.getBoundingClientRect();
			const sourceSize = ZOOM_LEVELS[zoomIndex];

			const sx = ((clientX - rect.left) / rect.width) * this.mainCanvas.width;
			const sy = ((clientY - rect.top) / rect.height) * this.mainCanvas.height;

			zoomCtx.imageSmoothingEnabled = false;
			zoomCtx.clearRect(0, 0, ZOOM_SIZE, ZOOM_SIZE);
			zoomCtx.drawImage(
				this.mainCanvas,
				sx - sourceSize / 2,
				sy - sourceSize / 2,
				sourceSize,
				sourceSize,
				0,
				0,
				ZOOM_SIZE,
				ZOOM_SIZE
			);

			loupe.style.left =
				Math.min(Math.max(clientX - wrapRect.left - ZOOM_SIZE / 2, 0), wrapRect.width - ZOOM_SIZE) +
				'px';
			loupe.style.top =
				Math.min(Math.max(clientY - wrapRect.top - ZOOM_SIZE / 2, 0), wrapRect.height - ZOOM_SIZE) +
				'px';
			loupe.style.display = 'block';
		};

		const cycleZoom = () => {
			zoomIndex = (zoomIndex + 1) % ZOOM_LEVELS.length;
			drawLoupe(lastX, lastY);
		};

		this.mainCanvas.addEventListener('click', () => {
			if (suppressClick) {
				suppressClick = false;
				return;
			}
			cycleZoom();
		});

		if (canHover) {
			this.mainCanvas.addEventListener('mousemove', (e) => {
				lastX = e.clientX;
				lastY = e.clientY;
				drawLoupe(e.clientX, e.clientY);
			});

			this.mainCanvas.addEventListener('mouseleave', () => {
				loupe.style.display = 'none';
			});
		}

		if (canTouch) {
			canvasWrap.addEventListener('contextmenu', (e) => e.preventDefault());

			let touchTimer = null;
			let touchStartX = 0;
			let touchStartY = 0;
			let loupeActive = false;

			canvasWrap.addEventListener(
				'touchstart',
				(e) => {
					const touch = e.touches[0];
					touchStartX = touch.clientX;
					touchStartY = touch.clientY;
					loupeActive = false;
					touchTimer = setTimeout(() => {
						loupeActive = true;
						lastX = touch.clientX;
						lastY = touch.clientY;
						drawLoupe(lastX, lastY);
					}, 300);
				},
				{ passive: true }
			);

			canvasWrap.addEventListener(
				'touchmove',
				(e) => {
					const touch = e.touches[0];
					if (loupeActive) {
						e.preventDefault();
						lastX = touch.clientX;
						lastY = touch.clientY;
						drawLoupe(lastX, lastY);
					} else if (Math.hypot(touch.clientX - touchStartX, touch.clientY - touchStartY) > 10) {
						clearTimeout(touchTimer);
					}
				},
				{ passive: false }
			);

			const endTouch = () => {
				clearTimeout(touchTimer);
				if (loupeActive) suppressClick = true;
				loupeActive = false;
				loupe.style.display = 'none';
			};
			canvasWrap.addEventListener('touchend', endTouch);
			canvasWrap.addEventListener('touchcancel', endTouch);
		}
	}

	loadImage(file) {
		const reader = new FileReader();
		reader.onload = (e) => {
			const img = new Image();
			img.onload = () => {
				this.img = img;

				this.mainCanvas.width = img.width;
				this.mainCanvas.height = img.height;
				this.mainCanvas.style.display = 'block';
				this.coverBtn.style.visibility = 'visible';

				this.fileUploadLabel.style.display = 'none';
				this.fileInput.style.display = 'none';

				this.extractChannels();
				this.render();
			};
			img.src = e.target.result;
		};
		reader.readAsDataURL(file);
	}

	extractChannels() {
		if (!this.img) return;
		this.cachedChannels.red = extractRGBChannel(this.img, 'red');
		this.cachedChannels.green = extractRGBChannel(this.img, 'green');
		this.cachedChannels.blue = extractRGBChannel(this.img, 'blue');
		this.layerCache = { red: null, green: null, blue: null };
		this.layerSignature = { red: null, green: null, blue: null };
	}

	exportJPG() {
		if (!this.mainCanvas) return;
		const link = document.createElement('a');
		link.download = 'generated-model.jpg';
		link.href = this.mainCanvas.toDataURL('image/jpeg', 1.0);
		link.click();
	}

	exportLayers() {
		const colorNames = {
			red: this.params.redColor,
			green: this.params.greenColor,
			blue: this.params.blueColor
		};

		const downloadNext = (i) => {
			if (i >= CHANNELS.length) return;
			const layer = CHANNELS[i];
			const riso = this.buildLayer(layer);
			if (!riso) {
				setTimeout(() => downloadNext(i + 1), 100);
				return;
			}

			const canvas = document.createElement('canvas');
			canvas.width = this.mainCanvas.width;
			canvas.height = this.mainCanvas.height;
			const ctx = canvas.getContext('2d');
			ctx.fillStyle = '#ffffff';
			ctx.fillRect(0, 0, canvas.width, canvas.height);
			riso.draw(canvas);

			canvas.toBlob(
				(blob) => {
					if (!blob) {
						setTimeout(() => downloadNext(i + 1), 100);
						return;
					}
					const link = document.createElement('a');
					link.download = (colorNames[layer] || layer) + '-layer.jpg';
					link.href = URL.createObjectURL(blob);
					link.click();
					setTimeout(() => downloadNext(i + 1), 500);
				},
				'image/jpeg',
				1.0
			);
		};

		downloadNext(0);
	}
}

new RisoLab();

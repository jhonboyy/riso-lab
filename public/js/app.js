		'An RGB channel is one of the three color channels within the RGB (Red, Green, Blue) color model. An RGB image comprises three distinct channels, with each aligning to one of these primary colors. <br><br>The image is generated by seamlessly merging these channels. Each channel encompasses intensity values for its specific color, and when amalgamated, they yield the complete spectrum of colors. In this particular instance, we are dividing the three color spectrums into layers.',
	patternItem:
		'A pattern is a repeated and recognizable design or sequence. It can refer to a regular or recurring form, arrangement, or behavior. <br><br>The Risograph printing process involves creating a stencil from a digital file and then using it to transfer ink onto paper. In this case, we convert tints to patterns for printing.',
	angleItem:
		'In this input, you have the option to specify your preferred angle. By doing so, you can dynamically adjust the rotation of the pattern.',
	frecuencyItem:
		'Here, you can input the frequency of the pattern, which determines the saturation and definition of the pattern itself.<br><br> A higher number indicates a bigger and less defined pattern, while a smaller number results in a smaller size of the pattern, enhancing readability and definition. The minimum value for this input is 1. Working with small values will affect the performance.',
	intensityItem:
		'In this input, you can adjust the intensity of the pattern, influencing the color saturation. A high number can signify a loss of the pattern.',
	fileButton:
		'You can upload your images in JPG and PNG formats. I am not using a cloud, so everything is managed locally :).<br><br> I recommend not uploading heavy images (< 1mb) for optimal performance. If you plan to print the images right after using this tool, I suggest uploading them while maintaining the printing proportions (A4/A3).'
